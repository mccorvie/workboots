from pathlib import Path

log = logging.getLogger("explore-server")

DEFAULT_EXPLORE_ROOT = Path.home() / ".local/share/tauceti-explore"
EMBEDDING_MAX_LENGTH = 512   # lean_explore.search.engine (1.3.0)
RERANKER_MAX_LENGTH = 256    # lean_explore.search.engine (1.3.0)


# --------------------------------------------------------------------------- engine

def make_engine_class():
    """Build the pinned-directory SearchEngine subclass (imports torch lazily)."""
    from lean_explore.search.engine import SearchEngine
    from lean_explore.search.scoring import fuzzy_name_score, normalize_dependency_counts, normalize_scores
    from lean_explore.search.tokenization import is_autogenerated

    class PinnedSearchEngine(SearchEngine):
        """SearchEngine over an explicit data directory (1.3.0 derives the BM25 paths
        from an import-time Config, so multi-pin serving needs this hook)."""

        def __init__(self, data_dir: Path, embedding_client, reranker_client):
            self._pin_dir = data_dir
            super().__init__(
                db_url=f"sqlite+aiosqlite:///{data_dir / 'lean_explore.db'}",
                embedding_client=embedding_client,
                reranker_client=reranker_client,
                faiss_index_path=data_dir / "informalization_faiss.index",
                faiss_ids_map_path=data_dir / "informalization_faiss_ids_map.json",
                use_local_data=True,
            )

        def _validate_paths(self) -> None:  # called at the end of SearchEngine.__init__
            self._bm25_spaced_path = self._pin_dir / "bm25_name_spaced"
            self._bm25_raw_path = self._pin_dir / "bm25_name_raw"
            self._bm25_ids_map_path = self._pin_dir / "bm25_ids_map.json"
            super()._validate_paths()

        async def search_scored(self, query: str, limit: int, rerank_top: int, faiss_k: int, bm25_k: int):
            """Same pipeline as SearchEngine.search (1.3.0) but returns (Declaration, score)."""
            if not query.strip():
                return []
            self._ensure_bm25_loaded()
            bm25_k = max(1, min(bm25_k, len(self._all_declaration_ids)))  # bm25s raises if k > corpus (small slices)
            bm25_map = self._retrieve_bm25_candidates(query, bm25_k)
            semantic_map = await self._retrieve_semantic_candidates(query, faiss_k)
            rrf_scores = self._compute_rrf_scores(bm25_map, semantic_map)
            if not rrf_scores:
                return []
            boosted, decls = await self._apply_dependency_boost(rrf_scores)
            top_n = rerank_top if rerank_top and rerank_top > 0 else limit
            scored = [(decls[cid], s) for cid, s in boosted[:top_n] if cid in decls]
            if not (rerank_top and rerank_top > 0):
                out = [(d, s) for d, s in scored if not is_autogenerated(d.name)]
                return out[:limit]
            documents = [f"{d.name}: {d.informalization}" if d.informalization else d.name for d, _ in scored]
            rr = await self.reranker_client.rerank(query, documents)
            fuzzy = [fuzzy_name_score(query, d.name) for d, _ in scored]
            bm25_inf = self._compute_bm25_on_informalizations(query, scored)
            dep_counts = self._compute_candidate_dependency_counts(scored)
            n_rr, n_fz, n_bm, n_dp = (normalize_scores(rr.scores), normalize_scores(fuzzy),
                                      normalize_scores(bm25_inf), normalize_dependency_counts(dep_counts))
            final = []
            for i, (d, _) in enumerate(scored):
                s = 1.0 * n_rr[i] + 0.4 * n_bm[i] + 0.2 * n_dp[i]
                if fuzzy[i] >= 0.7:
                    s += 1.0 * n_fz[i]
                final.append(s)
            combined = sorted(zip(scored, final), key=lambda x: x[1], reverse=True)
            out = [(d, s) for (d, _), s in combined if not is_autogenerated(d.name)]
            return out[:limit]

    return PinnedSearchEngine


class Pin:
    def __init__(self, name: str, directory: Path, engine, manifest: dict, meta: dict[str, tuple[str, bool]]):
        self.name, self.dir, self.engine, self.manifest, self.meta = name, directory, engine, manifest, meta


class Service:
    def __init__(self, a: argparse.Namespace):
        self.a = a
        self.lock = threading.Lock()
        self.loop = asyncio.new_event_loop()
        threading.Thread(target=self.loop.run_forever, name="engine-loop", daemon=True).start()
        self.pins: dict[str, Pin] = {}
        self.started_at = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        self._load()

    def _run(self, coro, timeout: float):
        return asyncio.run_coroutine_threadsafe(coro, self.loop).result(timeout=timeout)

    def _load(self) -> None:
        a = self.a
        import torch
        torch.manual_seed(0)
        if a.threads:
            torch.set_num_threads(a.threads)
        from huggingface_hub import snapshot_download
        from lean_explore.util.embedding_client import EmbeddingClient
        from lean_explore.util.reranker_client import RerankerClient

        dirs = [(p, a.explore_root / p) for p in a.pin] if a.pin else sorted(
            (d.name, d) for d in a.explore_root.iterdir() if d.is_dir() and (d / "MANIFEST.json").exists() and d.name != "upstream")
        if not dirs:
            sys.exit(f"no pins found under {a.explore_root}")
        manifests = {p: json.loads((d / "MANIFEST.json").read_text()) for p, d in dirs}
        emb = {(m["models"]["embedding"]["id"], m["models"]["embedding"]["revision"]) for m in manifests.values()}
        rer = {(m["models"]["reranker"]["id"], m["models"]["reranker"]["revision"]) for m in manifests.values()}
        if len(emb) != 1 or len(rer) != 1:
            sys.exit(f"pins disagree on model pins: embedding={emb} reranker={rer}; serve them from separate processes")
        (emb_id, emb_rev), (rer_id, rer_rev) = emb.pop(), rer.pop()
        emb_rev = a.embedding_revision or emb_rev
        rer_rev = a.reranker_revision or rer_rev
        emb_path = snapshot_download(emb_id, revision=emb_rev, local_files_only=not a.allow_download)
        rer_path = snapshot_download(rer_id, revision=rer_rev, local_files_only=not a.allow_download)
        log.info("loading embedder %s@%s and reranker %s@%s on %s", emb_id, emb_rev[:12], rer_id, rer_rev[:12], a.device)
        self.embedder = EmbeddingClient(model_name=emb_path, device=a.device, max_length=EMBEDDING_MAX_LENGTH, batch_size=8)
        self.reranker = RerankerClient(model_name=rer_path, device=a.device, max_length=RERANKER_MAX_LENGTH, batch_size=a.rerank_batch_size)
        self.models = {"embedding": {"id": emb_id, "revision": emb_rev, "path": emb_path},
                       "reranker": {"id": rer_id, "revision": rer_rev, "path": rer_path}, "device": a.device,
                       "torch": torch.__version__, "torch_threads": torch.get_num_threads()}
        Engine = make_engine_class()
        for p, d in dirs:
            engine = Engine(d, self.embedder, self.reranker)
            con = sqlite3.connect(f"file:{d / 'lean_explore.db'}?mode=ro", uri=True)
            meta = {}
            if con.execute("SELECT 1 FROM sqlite_master WHERE name='tauceti_meta'").fetchone():
                meta = {n: (k, bool(m)) for n, k, m in con.execute("SELECT name, kind, is_mathlib FROM tauceti_meta")}
            con.close()
            self.pins[p] = Pin(p, d, engine, manifests[p], meta)
            log.info("pin %s: %d declarations (%s)", p, manifests[p]["counts"]["declarations"], d)
        self.default_pin = a.default_pin or dirs[0][0]
        if self.default_pin not in self.pins:
            sys.exit(f"--default-pin {self.default_pin} not loaded")
        if a.warmup:
            t0 = time.time()
            self.search("compact set continuous image", 3, self.default_pin)
            log.info("warmup search in %.0f ms", (time.time() - t0) * 1000)

    def health(self, pin: str | None = None) -> dict:
        pin = pin or self.default_pin
        m = self.pins[pin].manifest
        src = m.get("source") or {}
        core = {"pin": pin, **{k: m.get(k) or src.get(k) for k in ("tauceti_sha", "mathlib_rev", "lean_toolchain", "decls_sha256")}}
        return {"ok": True, "tool": "explore", "manifest": {
            **core, "tool": "explore", "default_pin": pin, "pins": {n: pn.manifest for n, pn in self.pins.items()},
            "lean_explore": importlib.metadata.version("lean-explore"), "python": sys.version.split()[0],
            "models": self.models, "search_defaults": {"rerank_top": self.a.rerank_top, "faiss_k": self.a.faiss_k, "bm25_k": self.a.bm25_k, "max_k": self.a.max_k},
            "started_at": self.started_at,
        }}

    def search(self, q: str, k: int, pin_name: str, rerank_top: int | None = None) -> dict:
        pin = self.pins[pin_name]
        rt = self.a.rerank_top if rerank_top is None else rerank_top
        t0 = time.time()
        with self.lock:
            results = self._run(pin.engine.search_scored(q, k, rt, self.a.faiss_k, self.a.bm25_k), self.a.timeout)
        hits = []
        for d, score in results:
            kind, _ = pin.meta.get(d.name, ("", False))
            hits.append({"name": d.name, "kind": kind, "module": d.module, "signature": d.source_text,
                         "description": d.informalization or "", "score": round(float(score), 6)})
        return {"tool": "explore", "pin": pin_name, "k": k, "rerank_top": rt, "ms": int((time.time() - t0) * 1000), "hits": hits}


# --------------------------------------------------------------------------- http

SERVICE: Service | None = None


class Handler(BaseHTTPRequestHandler):
    socket_pin: str | None = None   # set per listening socket (subclass); None = service default
    server_version = "tauceti-explore/0.1"
    protocol_version = "HTTP/1.1"

    def address_string(self) -> str:  # client_address is '' on unix sockets
        ca = self.client_address
        return ca[0] if isinstance(ca, tuple) and ca else "unix"

    def log_message(self, fmt, *args):
        log.info("%s %s", self.address_string(), fmt % args)

    def _send(self, status: int, body: dict) -> None:
        data = json.dumps(body, ensure_ascii=False, separators=(",", ":")).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(data)

    def do_GET(self) -> None:
        assert SERVICE is not None
        url = urllib.parse.urlsplit(self.path)
        qs = urllib.parse.parse_qs(url.query, keep_blank_values=True)
        try:
            if url.path in ("/health", "/"):
                return self._send(HTTPStatus.OK, SERVICE.health(self.socket_pin))
            if url.path != "/search":
                return self._send(HTTPStatus.NOT_FOUND, {"error": f"no such endpoint {url.path}; use /health or /search?q=&k="})
            q = (qs.get("q") or [""])[0].strip()
            if not q:
                return self._send(HTTPStatus.BAD_REQUEST, {"error": "missing or empty q"})
            if len(q) > 2000:
                return self._send(HTTPStatus.BAD_REQUEST, {"error": "q longer than 2000 characters"})
            try:
                k = int((qs.get("k") or [str(SERVICE.a.default_k)])[0])
            except ValueError:
                return self._send(HTTPStatus.BAD_REQUEST, {"error": "k must be an integer"})
            k = max(1, min(k, SERVICE.a.max_k))
            pin = (qs.get("pin") or [self.socket_pin or SERVICE.default_pin])[0]
            if pin not in SERVICE.pins:
                return self._send(HTTPStatus.NOT_FOUND, {"error": f"unknown pin {pin!r}; loaded: {sorted(SERVICE.pins)}"})
            rt = None
            if "rerank_top" in qs:
                try:
                    rt = max(0, min(int(qs["rerank_top"][0]), 200))
                except ValueError:
                    return self._send(HTTPStatus.BAD_REQUEST, {"error": "rerank_top must be an integer"})
            return self._send(HTTPStatus.OK, SERVICE.search(q, k, pin, rt))
        except TimeoutError:
            return self._send(HTTPStatus.GATEWAY_TIMEOUT, {"error": "search timed out"})
        except Exception as exc:  # keep the service up; report the error
            log.exception("search failed")
            return self._send(HTTPStatus.INTERNAL_SERVER_ERROR, {"error": f"{type(exc).__name__}: {exc}"})


class UnixHTTPServer(socketserver.ThreadingMixIn, socketserver.UnixStreamServer):
    daemon_threads = True
    allow_reuse_address = True

    def __init__(self, path: str, handler, mode: int):
        self._mode = mode
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        if p.exists():
            p.unlink()
        super().__init__(path, handler)

    def server_bind(self):
        super().server_bind()
        os.chmod(self.server_address, self._mode)

    def get_request(self):
        sock, _ = super().get_request()
        return sock, ("unix", 0)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--explore-root", type=Path, default=DEFAULT_EXPLORE_ROOT)
    ap.add_argument("--pin", action="append", help="pin directory name under --explore-root; repeatable; default: all with MANIFEST.json")
    ap.add_argument("--default-pin")
    ap.add_argument("--socket-dir", help="one socket per loaded pin at <dir>/<pin>/explore.sock (dir 0755), "
                    "e.g. $XDG_RUNTIME_DIR/tauceti-explore; each defaults to its own pin")
    ap.add_argument("--unix-socket", help="single extra socket serving the default pin (legacy/testing)")
    ap.add_argument("--socket-mode", default="0666")
    ap.add_argument("--port", type=int, help="optional loopback TCP listener")
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--rerank-top", type=int, default=25, help="cross-encoder depth (0 disables reranking)")
    ap.add_argument("--rerank-batch-size", type=int, default=32)
    ap.add_argument("--faiss-k", type=int, default=1000)
    ap.add_argument("--bm25-k", type=int, default=1000)
    ap.add_argument("--default-k", type=int, default=10)
    ap.add_argument("--max-k", type=int, default=50)
    ap.add_argument("--device", default="cpu")
    ap.add_argument("--threads", type=int, default=8, help="torch intra-op threads (0 = library default)")
    ap.add_argument("--timeout", type=float, default=60.0)
    ap.add_argument("--embedding-revision"); ap.add_argument("--reranker-revision")
    ap.add_argument("--allow-download", action="store_true", help="let huggingface_hub fetch missing model files (off: offline only)")
    ap.add_argument("--no-warmup", dest="warmup", action="store_false")
    ap.add_argument("-v", "--verbose", action="store_true")
    a = ap.parse_args()
    if not a.unix_socket and not a.port and not a.socket_dir:
        ap.error("need --socket-dir, --unix-socket and/or --port")
    if a.device == "cpu":
        os.environ.setdefault("CUDA_VISIBLE_DEVICES", "")
    logging.basicConfig(level=logging.DEBUG if a.verbose else logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    for noisy in ("sentence_transformers", "transformers", "huggingface_hub", "lean_explore"):
        logging.getLogger(noisy).setLevel(logging.WARNING)

    global SERVICE
    SERVICE = Service(a)
    servers = []
    sockets: list[str] = []
    if a.socket_dir:
        root = Path(a.socket_dir)
        root.mkdir(parents=True, exist_ok=True)
        for name in SERVICE.pins:
            d = root / name
            d.mkdir(parents=True, exist_ok=True)
            os.chmod(d, 0o755)
            h = type("PinHandler", (Handler,), {"socket_pin": name})
            servers.append(UnixHTTPServer(str(d / "explore.sock"), h, int(a.socket_mode, 8)))
            sockets.append(str(d / "explore.sock"))
            log.info("pin %s listening on %s", name, d / "explore.sock")
    if a.unix_socket:
        sockets.append(a.unix_socket)
        servers.append(UnixHTTPServer(a.unix_socket, Handler, int(a.socket_mode, 8)))
        log.info("listening on unix socket %s (mode %s)", a.unix_socket, a.socket_mode)
    if a.port:
        servers.append(ThreadingHTTPServer((a.host, a.port), Handler))
        log.info("listening on http://%s:%d", a.host, a.port)
    threads = [threading.Thread(target=s.serve_forever, daemon=True) for s in servers]
    for t in threads:
        t.start()
    try:
        while True:
            time.sleep(3600)
    except KeyboardInterrupt:
        pass
    finally:
        for s in servers:
            s.shutdown()
        for sp in sockets:
            if Path(sp).exists():
                Path(sp).unlink()


if __name__ == "__main__":
    main()
