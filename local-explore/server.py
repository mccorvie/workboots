#!/usr/bin/env python3
"""TauCeti `explore` search service: LeanExplore's local engine behind the plan's wire protocol.

    server.py --socket-dir $XDG_RUNTIME_DIR/tauceti-explore [--port 8089]
              (one socket per pin: <dir>/<pin>/explore.sock; /health and /search default to that pin)
              [--explore-root ~/.local/share/tauceti-explore] [--pin b3-11bc13335fb9 ...]

Wire protocol (workboots-plan.md, "Search service wire protocol"):
  GET /health            -> {"ok": true, "tool": "explore", "manifest": {...}}
  GET /search?q=&k=10    -> {"tool": "explore", "pin": "<pin>", "hits": [{name, kind, module,
                             signature, description, score}, ...]}
  errors                 -> 4xx/5xx with {"error": "..."}
  optional: &pin=<pin> selects one of the loaded pins (default: --default-pin or the first).

Determinism: one SearchEngine per pin over a frozen directory; the embedder and reranker are
local (Qwen3-Embedding-0.6B / Qwen3-Reranker-0.6B at pinned revisions, shared across pins),
float32 on CPU with a fixed thread count; requests are serialised; no network at query time.
The ranking math is LeanExplore 1.3.0's own (`SearchEngine.search` with rerank), replicated
here only to keep the final scores, which the upstream API discards.
"""

from __future__ import annotations

import argparse
import asyncio
import datetime as dt
import importlib.metadata
